"""
文档标题识别提示词（快速版）
只判断候选内容是否为标题
"""

RELATION_PREDICTION_PROMPT = """你是文档结构分析专家。给定一个候选列表（按顺序），判断每个候选是否为标题。

**任务**：识别哪些是真正的标题，过滤掉注释、说明、引用等非标题内容。

## 输入格式
```json
[
  {"id": 0, "text": "第一章 总则", "page": "1"},
  {"id": 5, "text": "注：本章适用于所有投标人", "page": "3"},
  {"id": 10, "text": "第二章 招标文件", "page": "5"}
]
```

## 输出格式
只输出**确认为标题**的候选：
```json
[
  {"id": 0},
  {"id": 10}
]
```

---

## 标题特征

**是标题**的特征：
- 有明显的编号：`第一章`、`一、`、`1.`、`（一）`、`1.1` 等
- 简短精炼（通常不超过 50 字）
- 描述性短语，不是完整句子
- 常见标题关键词：总则、概述、要求、说明、附件、附录等

**不是标题**的特征：
- 以"注：""备注：""说明："开头
- 完整的长句子（包含多个逗号、谓语动词、句号）
- 引用性文字：`详见第一章`、`参见附件1`、`根据第X条规定`
- 纯数字或符号（如页码）
- 空白或无意义内容

---

## 示例

**输入**：
```json
[
  {"id": 0, "text": "第一章 总则"},
  {"id": 5, "text": "注：本章适用于所有投标人。"},
  {"id": 10, "text": "第二章 招标文件"},
  {"id": 15, "text": "一、总体要求"},
  {"id": 20, "text": "根据第一章第二条的规定，投标人应当..."},
  {"id": 25, "text": "二、技术要求"},
  {"id": 30, "text": "详见附件 1"}
]
```

**输出**：
```json
[
  {"id": 0},    // 第一章 总则 - 是标题
  {"id": 10},   // 第二章 招标文件 - 是标题
  {"id": 15},   // 一、总体要求 - 是标题
  {"id": 25}    // 二、技术要求 - 是标题
]
```

**说明**：
- `id: 5` - "注：..." 开头，是注释，不输出
- `id: 20` - 完整句子，是正文，不输出
- `id: 30` - 引用性文字，不输出

## 重要约束

1. **只输出标题的 id**：非标题不要出现在输出中
2. **输出格式**：只包含 `{"id": 数字}` 字段
3. **只输出 JSON 数组**：不要添加任何解释

---

现在，请分析以下标题候选列表：

<这里插入标题候选列表JSON>

只输出 JSON 数组，不要添加任何解释。
"""


def get_relation_prediction_prompt(candidates_json: str = "<这里插入标题候选列表JSON>") -> str:
    """
    获取标题关系预测提示词（域划分版 / 无正则）

    Args:
        candidates_json: 标题候选列表的 JSON 字符串

    Returns:
        格式化后的提示词
    """
    return RELATION_PREDICTION_PROMPT.replace(
        "<这里插入标题候选列表JSON>",
        candidates_json
    )